// Arabic joining types (Unicode ArabicShaping.txt, UAX #9 / Core Spec
// §9.2). They decide which contextual form an OpenType shaper asks the font
// for — the isol/init/medi/fina masks in shape.go. The Presentation Forms-B
// shaper (arabic_shape.go) carries its own, smaller table because it can
// only map the letters Forms-B has glyphs for; this one covers every
// joining script Unicode defines (Arabic with its Persian, Urdu and
// African extensions, Syriac, N'Ko, Mongolian, Phags-pa, Manichaean, …).
//
// Generated from the Unicode Character Database 16.0.0.

type joiningType uint8

const (
	joinU joiningType = iota // non-joining
	joinR                    // right-joining: connects to the preceding letter only
	joinL                    // left-joining: connects to the following letter only
	joinD                    // dual-joining
	joinC                    // join-causing (tatweel, ZWJ)
	joinT                    // transparent (marks): skipped when finding neighbours
)

type joiningRange struct {
	lo, hi rune
	t      joiningType
}

