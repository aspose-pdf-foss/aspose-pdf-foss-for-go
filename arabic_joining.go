// joiningTypeOf returns r's joining type. Code points the data file does not
// list are transparent when they are marks or format characters, and
// non-joining otherwise — the file's own stated default.
func joiningTypeOf(r rune) joiningType {
	lo, hi := 0, len(joiningRanges)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < joiningRanges[mid].lo:
			hi = mid - 1
		case r > joiningRanges[mid].hi:
			lo = mid + 1
		default:
			return joiningRanges[mid].t
		}
	}
	if unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf) {
		return joinT
	}
	return joinU
}

// joinsPreceding reports whether a letter of this type can connect to the
// letter before it (on its right, in an RTL line).
func (t joiningType) joinsPreceding() bool { return t == joinR || t == joinD || t == joinC }

// joinsFollowing reports whether a letter of this type can connect to the
// letter after it.
func (t joiningType) joinsFollowing() bool { return t == joinL || t == joinD || t == joinC }
